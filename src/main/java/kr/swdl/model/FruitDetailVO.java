package kr.swdl.model;

public class FruitDetailVO {
	private int itemCode;
    private String itemName;
    private String kindName;
    private String origin;
    private String name;
    private int price;
    private int quantity;
    private double weight;
    private long totalPrice;
    private String memberRealName;  // m.name
    private String memberName;      // m.member_name (NULL 가능)
    private String address;
    private String phone;
    private String email;
    private String adminName;
	public int getItemCode() {
		return itemCode;
	}
	public void setItemCode(int itemCode) {
		this.itemCode = itemCode;
	}
	public String getItemName() {
		return itemName;
	}
	public void setItemName(String itemName) {
		this.itemName = itemName;
	}
	public String getKindName() {
		return kindName;
	}
	public void setKindName(String kindName) {
		this.kindName = kindName;
	}
	public String getOrigin() {
		return origin;
	}
	public void setOrigin(String origin) {
		this.origin = origin;
	}
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
	public int getPrice() {
		return price;
	}
	public void setPrice(int price) {
		this.price = price;
	}
	public int getQuantity() {
		return quantity;
	}
	public void setQuantity(int quantity) {
		this.quantity = quantity;
	}
	public double getWeight() {
		return weight;
	}
	public void setWeight(double weight) {
		this.weight = weight;
	}
	public long getTotalPrice() {
		return totalPrice;
	}
	public void setTotalPrice(long totalPrice) {
		this.totalPrice = totalPrice;
	}
	public String getMemberRealName() {
		return memberRealName;
	}
	public void setMemberRealName(String memberRealName) {
		this.memberRealName = memberRealName;
	}
	public String getMemberName() {
		return memberName;
	}
	public void setMemberName(String memberName) {
		this.memberName = memberName;
	}
	public String getAddress() {
		return address;
	}
	public void setAddress(String address) {
		this.address = address;
	}
	public String getPhone() {
		return phone;
	}
	public void setPhone(String phone) {
		this.phone = phone;
	}
	public String getEmail() {
		return email;
	}
	public void setEmail(String email) {
		this.email = email;
	}
	public String getAdminName() {
		return adminName;
	}
	public void setAdminName(String adminName) {
		this.adminName = adminName;
	}
	@Override
	public String toString() {
		return "FruitDetailVO [itemCode=" + itemCode + ", itemName=" + itemName + ", kindName=" + kindName + ", origin="
				+ origin + ", name=" + name + ", price=" + price + ", quantity=" + quantity + ", weight=" + weight
				+ ", totalPrice=" + totalPrice + ", memberRealName=" + memberRealName + ", memberName=" + memberName
				+ ", address=" + address + ", phone=" + phone + ", email=" + email + ", adminName=" + adminName + "]";
	}
	
    
    
    
}
